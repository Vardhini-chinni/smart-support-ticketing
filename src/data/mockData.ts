/**
 * Deterministic rule-based classification function (Python Classification module simulation).
 * Uses clear keyword matching rules without claiming machine learning.
 */
export function classifyTicketIssue(title: string, description: string): ClassificationResult {
  const combined = `${title} ${description}`.toLowerCase();

  const rules: Array<{
    category: TicketCategory;
    categoryId: string;
    assignedTeam: SupportTeam;
    keywords: string[];
  }> = [
    {
      category: 'Payment',
      categoryId: 'CAT-01',
      assignedTeam: 'Payment Support',
      keywords: ['payment', 'paid', 'transaction', 'deducted', 'upi', 'card', 'charge', 'billing', 'invoice', 'debited'],
    },
    {
      category: 'Technical',
      categoryId: 'CAT-02',
      assignedTeam: 'Technical Support',
      keywords: ['login', 'password', 'crash', 'error', 'bug', 'timeout', 'otp', 'server', 'failed', 'exception'],
    },
    {
      category: 'Refund',
      categoryId: 'CAT-03',
      assignedTeam: 'Refund Support',
      keywords: ['refund', 'money back', 'return', 'reimbursement', 'reversal', 'credit back'],
    },
    {
      category: 'Delivery',
      categoryId: 'CAT-04',
      assignedTeam: 'Delivery Support',
      keywords: ['delivery', 'shipping', 'parcel', 'courier', 'tracking', 'delayed', 'shipment', 'package'],
    },
    {
      category: 'Account',
      categoryId: 'CAT-05',
      assignedTeam: 'Account Support',
      keywords: ['account', 'profile', 'verification', 'kyc', 'email', 'locked', 'deactivate'],
    },
  ];

  for (const rule of rules) {
    const matched = rule.keywords.filter((kw) => combined.includes(kw));
    if (matched.length > 0) {
      return {
        category: rule.category,
        categoryId: rule.categoryId,
        assignedTeam: rule.assignedTeam,
        matchedKeywords: matched,
        ruleExplanation: `Matched rule keywords [${matched.join(', ')}] → Routed to ${rule.assignedTeam}`,
      };
    }
  }

  return {
    category: 'General',
    categoryId: 'CAT-06',
    assignedTeam: 'General Support',
    matchedKeywords: ['default-rule'],
    ruleExplanation: 'No domain-specific keywords matched → Defaulted to General Support',
  };
}

export function buildEscalationChain(
  currentLevel: EscalationLevel,
  isResolved: boolean,
  primaryAgentName = 'Aarav Mehta',
  primaryAgentId = 'AG-201',
  baseDate = '2026-09-26 09:15',
  reason = 'SLA threshold exceeded; requires higher-tier verification'
): EscalationChainStep[] {
  const levelOrder: Array<'Level 1' | 'Level 2' | 'Senior Level' | 'Manager Level'> = [
    'Level 1',
    'Level 2',
    'Senior Level',
    'Manager Level',
  ];

  const currentIdx =
    currentLevel === 'None' ? 0 : levelOrder.indexOf(currentLevel as 'Level 1' | 'Level 2' | 'Senior Level' | 'Manager Level');

  const stepsConfig: Array<{
    level: 'Level 1' | 'Level 2' | 'Senior Level' | 'Manager Level';
    nodeLabel: string;
    agentId: string;
    agentName: string;
    role: string;
    nodeType: 'agent' | 'manager';
  }> = [
    {
      level: 'Level 1',
      nodeLabel: 'Level 1 Agent',
      agentId: primaryAgentId,
      agentName: primaryAgentName,
      role: 'Tier 1 Support Specialist',
      nodeType: 'agent',
    },
    {
      level: 'Level 2',
      nodeLabel: 'Level 2 Agent',
      agentId: 'AG-202',
      agentName: 'Priya Nair',
      role: 'Tier 2 Escalation Analyst',
      nodeType: 'agent',
    },
    {
      level: 'Senior Level',
      nodeLabel: 'Senior Agent',
      agentId: 'AG-208',
      agentName: 'Vikram Desai',
      role: 'Senior Escalation Lead',
      nodeType: 'agent',
    },
    {
      level: 'Manager Level',
      nodeLabel: 'Manager',
      agentId: 'AG-209',
      agentName: 'Ananya Sharma',
      role: 'Support Operations Manager',
      nodeType: 'manager',
    },
  ];

  return stepsConfig.map((step, idx) => {
    let status: 'passed' | 'current' | 'upcoming' | 'resolved' = 'upcoming';
    if (isResolved) {
      status = idx <= currentIdx ? 'resolved' : 'upcoming';
    } else if (currentLevel === 'None') {
      status = idx === 0 ? 'current' : 'upcoming';
    } else {
      if (idx < currentIdx) status = 'passed';
      else if (idx === currentIdx) status = 'current';
      else status = 'upcoming';
    }

    return {
      ...step,
      status,
      timestamp: idx <= currentIdx ? baseDate : undefined,
      reason: idx === currentIdx && currentLevel !== 'None' ? reason : undefined,
    };
  });
}

export function buildTimeline(params: {
  ticketId: string;
  createdAt: string;
  category: TicketCategory;
  assignedTeam: SupportTeam;
  assignedAgentName: string;
  status: 'Open' | 'In Progress' | 'Escalated' | 'Resolved';
  escalationLevel: EscalationLevel;
  escalationReason?: string;
}): TicketTimelineStep[] {
  const {
    ticketId,
    createdAt,
    category,
    assignedTeam,
    assignedAgentName,
    status,
    escalationLevel,
    escalationReason,
  } = params;

  const isEscalated = status === 'Escalated' || escalationLevel !== 'None';
  const isResolved = status === 'Resolved';

  return [
    {
      id: `${ticketId}-step-1`,
      stage: 'Ticket Created',
      title: 'Ticket Created',
      description: `Customer support request registered in DBMS with ID ${ticketId}.`,
      timestamp: createdAt,
      responsibleAgent: 'System Intake Portal',
      completed: true,
    },
    {
      id: `${ticketId}-step-2`,
      stage: 'Category Identified',
      title: 'Category Identified',
      description: `Rule-based classifier detected category: ${category}.`,
      timestamp: createdAt,
      responsibleAgent: 'Python Rule Classifier',
      completed: true,
    },
    {
      id: `${ticketId}-step-3`,
      stage: 'Assigned to Team',
      title: 'Assigned to Team',
      description: `Java routing logic mapped ${category} category to ${assignedTeam}.`,
      timestamp: createdAt,
      responsibleAgent: 'Java Routing Engine',
      completed: true,
    },
    {
      id: `${ticketId}-step-4`,
      stage: 'Assigned to Agent',
      title: 'Assigned to Agent',
      description: `Ticket allocated to ${assignedAgentName} (${assignedTeam}).`,
      timestamp: createdAt,
      responsibleAgent: assignedAgentName,
      completed: true,
      active: !isEscalated && !isResolved,
    },
    {
      id: `${ticketId}-step-5`,
      stage: 'Escalated',
      title: isEscalated ? `Escalated (${escalationLevel})` : 'Escalation Stage',
      description: isEscalated
        ? escalationReason || `Escalated to ${escalationLevel} for specialized resolution.`
        : 'No escalation triggered — handled within standard SLA.',
      timestamp: isEscalated ? createdAt : '—',
      responsibleAgent: isEscalated ? assignedAgentName : 'Not Triggered',
      completed: isEscalated,
      active: status === 'Escalated',
    },
    {
      id: `${ticketId}-step-6`,
      stage: 'Resolved',
      title: 'Resolved',
      description: isResolved
        ? `Issue verified and marked resolved by ${assignedAgentName}.`
        : 'Pending final resolution and customer confirmation.',
      timestamp: isResolved ? '2026-09-26 10:05' : 'Pending',
      responsibleAgent: isResolved ? assignedAgentName : 'Pending',
      completed: isResolved,
      active: isResolved,
    },
  ];
}

